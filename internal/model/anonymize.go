package model

import (
	"regexp"
	"strings"
	"time"
)

// Strategy is how an anonymization rule transforms a value.
type Strategy string

const (
	// StrategyRedact replaces the value with Replacement (default "[REDACTED]").
	StrategyRedact Strategy = "redact"
	// StrategyRemove deletes the header, query param, cookie, form field or
	// JSON member. For regex and path targets it behaves like redact.
	StrategyRemove Strategy = "remove"
	// StrategyHash replaces the value with a deterministic token derived from
	// HMAC-SHA256(secret, value), e.g. "h_3f9a1c0b7d2e4a51". The same input
	// always maps to the same token within a profile, so relationships
	// (same user across requests) survive anonymization.
	StrategyHash Strategy = "hash"
	// StrategyFake replaces the value with deterministic, format-preserving
	// fake data of kind Fake (an email stays a valid email, a 16-digit card
	// stays a Luhn-valid 16-digit card, a UUID stays a UUID, "AB-1234"
	// becomes "QX-8302"). Also keyed by the HMAC so it is consistent.
	StrategyFake Strategy = "fake"
	// StrategyMask keeps KeepPrefix/KeepSuffix characters and replaces the
	// rest with '*'.
	StrategyMask Strategy = "mask"
)

// RuleTarget is where an anonymization rule looks for values.
type RuleTarget string

const (
	// TargetHeader: Selector is a header name (case-insensitive).
	TargetHeader RuleTarget = "header"
	// TargetQuery: Selector is a query parameter name.
	TargetQuery RuleTarget = "query"
	// TargetCookie: Selector is a cookie name, in Cookie and Set-Cookie.
	TargetCookie RuleTarget = "cookie"
	// TargetJSON: Selector is a JSONPath subset applied to JSON bodies:
	// "$.user.email", "$.items[*].card", "$.items[0].id", "$..email"
	// (recursive descent by key name) and "$.*" wildcards.
	TargetJSON RuleTarget = "json"
	// TargetForm: Selector is a field name in an
	// application/x-www-form-urlencoded body.
	TargetForm RuleTarget = "form"
	// TargetRegex: Selector is an RE2 pattern applied to all textual values:
	// bodies, query values and header values. If the pattern has a capture
	// group, only the first group is replaced.
	TargetRegex RuleTarget = "regex"
	// TargetPath: Selector is a path template whose {named} segments are
	// anonymized, e.g. "/users/{id}/orders/{order_id}".
	TargetPath RuleTarget = "path"
)

// RuleScope is which side of the exchange a rule applies to.
type RuleScope string

const (
	ScopeBoth     RuleScope = "both"
	ScopeRequest  RuleScope = "request"
	ScopeResponse RuleScope = "response"
)

// FakeKind is the kind of fake value generated by StrategyFake.
type FakeKind string

const (
	FakeAuto       FakeKind = "auto" // detect from the value; falls back to character-class preserving
	FakeEmail      FakeKind = "email"
	FakeName       FakeKind = "name"
	FakePhone      FakeKind = "phone"
	FakeUUID       FakeKind = "uuid"
	FakeDigits     FakeKind = "digits"
	FakeIPv4       FakeKind = "ipv4"
	FakeCreditCard FakeKind = "credit_card"
	FakeString     FakeKind = "string" // same length, same character classes
)

// AnonymizationRule is one user-defined transformation.
type AnonymizationRule struct {
	ID          string     `json:"id"`
	Name        string     `json:"name"`
	Enabled     bool       `json:"enabled"`
	Target      RuleTarget `json:"target"`
	Selector    string     `json:"selector"`
	Scope       RuleScope  `json:"scope"`
	Strategy    Strategy   `json:"strategy"`
	Fake        FakeKind   `json:"fake,omitempty"`
	KeepPrefix  int        `json:"keep_prefix,omitempty"`
	KeepSuffix  int        `json:"keep_suffix,omitempty"`
	Replacement string     `json:"replacement,omitempty"`
}

// Detector names a built-in PII detector. Detectors scan every textual value
// (bodies, query values, non-redacted header values, cookie values) and
// transform matches with the profile's DetectorStrategy.
type Detector string

const (
	DetectEmail      Detector = "email"
	DetectCreditCard Detector = "credit_card" // Luhn-checked 13-19 digit numbers
	DetectSSN        Detector = "ssn"         // US social security numbers
	DetectPhone      Detector = "phone"       // E.164 and NANP formats
	DetectIPv4       Detector = "ipv4"
	DetectIPv6       Detector = "ipv6"
	DetectJWT        Detector = "jwt"
	DetectAWSKey     Detector = "aws_key" // AKIA/ASIA access key IDs
	DetectIBAN       Detector = "iban"
	DetectUUID       Detector = "uuid" // off by default: UUIDs are often harmless IDs
)

// AllDetectors lists every built-in detector in display order.
var AllDetectors = []Detector{
	DetectEmail, DetectCreditCard, DetectSSN, DetectPhone, DetectIPv4,
	DetectIPv6, DetectJWT, DetectAWSKey, DetectIBAN, DetectUUID,
}

// AnonymizationProfile is a named set of anonymization settings.
type AnonymizationProfile struct {
	ID          string `json:"id"`
	Name        string `json:"name"`
	Description string `json:"description,omitempty"`
	// Detectors enabled for this profile.
	Detectors []Detector `json:"detectors"`
	// DetectorStrategy is applied to detector matches. Default fake (auto).
	DetectorStrategy Strategy `json:"detector_strategy"`
	// RedactHeaders are header names whose values are always replaced with
	// deterministic hash tokens (an auth scheme prefix such as "Bearer " is
	// kept). Cookie and Set-Cookie are handled per cookie: names and
	// attributes are kept, values are hashed.
	RedactHeaders []string `json:"redact_headers"`
	// Rules run before detectors, in order.
	Rules []AnonymizationRule `json:"rules"`
	// OpaqueBodies controls bodies the engine cannot inspect (binary content
	// types, bodies still carrying a Content-Encoding, binary multipart
	// parts): "keep" (default) stores them unchanged; "fill" replaces them
	// with deterministic filler of identical length, so sizes stay realistic
	// for load tests but no original bytes are kept.
	OpaqueBodies string `json:"opaque_bodies"`
	// Secret keys the HMAC behind hash/fake. The API never returns it; an
	// empty secret on update keeps the stored one.
	Secret    string    `json:"secret,omitempty"`
	HasSecret bool      `json:"has_secret,omitempty"` // set by the API on output
	CreatedAt time.Time `json:"created_at"`
	UpdatedAt time.Time `json:"updated_at"`
}

// DefaultProfileID is the ID of the built-in profile that the store seeds on
// first open. Services with an empty ProfileID use it.
const DefaultProfileID = "default"

// DefaultAnonymizationProfile returns the built-in profile (without a
// secret; the store generates one when seeding).
func DefaultAnonymizationProfile() AnonymizationProfile {
	return AnonymizationProfile{
		ID:          DefaultProfileID,
		Name:        "Default",
		Description: "Hashes auth headers, session cookies and common credential fields (passwords, tokens, API keys), fakes person names, and replaces detected PII (emails, cards, SSNs, phone numbers, IPs, JWTs, AWS keys, IBANs) with consistent fake values.",
		Detectors: []Detector{
			DetectEmail, DetectCreditCard, DetectSSN, DetectPhone,
			DetectIPv4, DetectIPv6, DetectJWT, DetectAWSKey, DetectIBAN,
		},
		DetectorStrategy: StrategyFake,
		RedactHeaders: []string{
			"Authorization", "Proxy-Authorization", "Cookie", "Set-Cookie",
			"X-Api-Key", "X-Auth-Token", "X-Access-Token", "X-Csrf-Token",
			"X-Forwarded-For", "X-Real-Ip", "Forwarded",
		},
		Rules:        defaultRules(),
		OpaqueBodies: OpaqueKeep,
	}
}

// Values of AnonymizationProfile.OpaqueBodies.
const (
	OpaqueKeep = "keep"
	OpaqueFill = "fill"
)

// defaultRules are the credential and name rules of the built-in profile.
// IDs are stable so later releases can recognise them.
func defaultRules() []AnonymizationRule {
	var rules []AnonymizationRule
	add := func(id, name string, t RuleTarget, sel string, st Strategy, fake FakeKind) {
		rules = append(rules, AnonymizationRule{
			ID: "def-" + id, Name: name, Enabled: true, Target: t,
			Selector: sel, Scope: ScopeBoth, Strategy: st, Fake: fake,
		})
	}
	for _, k := range []string{"password", "passwd", "pass", "secret", "client_secret", "clientSecret", "pin", "cvv", "cvc"} {
		add("json-"+k, "JSON "+k, TargetJSON, "$.."+k, StrategyRedact, "")
	}
	for _, k := range []string{"access_token", "accessToken", "refresh_token", "refreshToken", "id_token", "idToken", "api_key", "apiKey", "token", "session_id", "sessionId"} {
		add("json-"+k, "JSON "+k, TargetJSON, "$.."+k, StrategyHash, "")
	}
	for _, k := range []string{"first_name", "firstName", "last_name", "lastName", "full_name", "fullName", "given_name", "family_name"} {
		add("json-"+k, "JSON "+k, TargetJSON, "$.."+k, StrategyFake, FakeName)
	}
	for _, k := range []string{"password", "passwd", "client_secret", "secret", "pin"} {
		add("form-"+k, "Form "+k, TargetForm, k, StrategyRedact, "")
	}
	for _, k := range []string{"access_token", "refresh_token", "api_key", "token"} {
		add("form-"+k, "Form "+k, TargetForm, k, StrategyHash, "")
	}
	for _, k := range []string{"access_token", "api_key", "apikey", "key", "token", "signature", "sig", "password", "secret", "session", "sessionid"} {
		add("query-"+k, "Query "+k, TargetQuery, k, StrategyHash, "")
	}
	return rules
}

// Redacted returns a copy safe to send to clients: Secret cleared and
// HasSecret set when there was one.
func (p AnonymizationProfile) Redacted() AnonymizationProfile {
	if p.Secret != "" {
		p.HasSecret = true
	}
	p.Secret = ""
	return p
}

// WithDefaults returns a copy with zero-valued fields defaulted.
func (p AnonymizationProfile) WithDefaults() AnonymizationProfile {
	if p.DetectorStrategy == "" {
		p.DetectorStrategy = StrategyFake
	}
	if p.Detectors == nil {
		p.Detectors = []Detector{}
	}
	if p.RedactHeaders == nil {
		p.RedactHeaders = []string{}
	}
	if p.Rules == nil {
		p.Rules = []AnonymizationRule{}
	}
	if p.OpaqueBodies == "" {
		p.OpaqueBodies = OpaqueKeep
	}
	for i := range p.Rules {
		r := &p.Rules[i]
		if r.Scope == "" {
			r.Scope = ScopeBoth
		}
		if r.Strategy == "" {
			r.Strategy = StrategyHash
		}
		if r.Strategy == StrategyFake && r.Fake == "" {
			r.Fake = FakeAuto
		}
	}
	return p
}

// Validate checks the profile's structure (after WithDefaults). The
// anonymize package performs deeper checks (JSONPath syntax).
func (p AnonymizationProfile) Validate() error {
	var pr problems
	if strings.TrimSpace(p.Name) == "" {
		pr.add("name is required")
	}
	if p.OpaqueBodies != OpaqueKeep && p.OpaqueBodies != OpaqueFill {
		pr.add("opaque_bodies %q must be keep or fill", p.OpaqueBodies)
	}
	if !validStrategy(p.DetectorStrategy) {
		pr.add("detector_strategy %q is not a strategy", p.DetectorStrategy)
	}
	known := map[Detector]bool{}
	for _, d := range AllDetectors {
		known[d] = true
	}
	for _, d := range p.Detectors {
		if !known[d] {
			pr.add("unknown detector %q", d)
		}
	}
	for i, r := range p.Rules {
		label := r.Name
		if label == "" {
			label = r.Selector
		}
		switch r.Target {
		case TargetHeader, TargetQuery, TargetCookie, TargetJSON, TargetForm, TargetPath:
		case TargetRegex:
			if _, err := regexp.Compile(r.Selector); err != nil {
				pr.add("rule %d (%s): invalid regex: %v", i+1, label, err)
			}
		default:
			pr.add("rule %d (%s): unknown target %q", i+1, label, r.Target)
		}
		if strings.TrimSpace(r.Selector) == "" {
			pr.add("rule %d: selector is required", i+1)
		}
		if r.Target == TargetJSON && !strings.HasPrefix(r.Selector, "$") {
			pr.add("rule %d (%s): JSON selector must start with $", i+1, label)
		}
		if r.Target == TargetPath && !strings.HasPrefix(r.Selector, "/") {
			pr.add("rule %d (%s): path selector must start with /", i+1, label)
		}
		switch r.Scope {
		case ScopeBoth, ScopeRequest, ScopeResponse:
		default:
			pr.add("rule %d (%s): unknown scope %q", i+1, label, r.Scope)
		}
		if !validStrategy(r.Strategy) {
			pr.add("rule %d (%s): unknown strategy %q", i+1, label, r.Strategy)
		}
		if r.Strategy == StrategyFake {
			switch r.Fake {
			case FakeAuto, FakeEmail, FakeName, FakePhone, FakeUUID, FakeDigits, FakeIPv4, FakeCreditCard, FakeString:
			default:
				pr.add("rule %d (%s): unknown fake kind %q", i+1, label, r.Fake)
			}
		}
		if r.KeepPrefix < 0 || r.KeepSuffix < 0 {
			pr.add("rule %d (%s): keep_prefix/keep_suffix must not be negative", i+1, label)
		}
	}
	return pr.err()
}

func validStrategy(s Strategy) bool {
	switch s {
	case StrategyRedact, StrategyRemove, StrategyHash, StrategyFake, StrategyMask:
		return true
	}
	return false
}

// AnonChange describes one value changed by anonymization, for previews.
type AnonChange struct {
	// Location is human readable: "request.header.Authorization",
	// "response.body $.user.email", "request.query.email", "request.path".
	Location string `json:"location"`
	// Source is the rule name or "detector:<name>" or "redact_headers".
	Source string `json:"source"`
	Before string `json:"before"`
	After  string `json:"after"`
}
